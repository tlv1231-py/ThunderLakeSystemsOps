export function getExercise(slug: string): ExerciseDef | undefined {
  return EXERCISES[slug];
}

export function getTravelSubstitution(slug: string): ExerciseDef | undefined {
  const ex = EXERCISES[slug];
  if (!ex || ex.isTravelSafe) return ex;
  if (ex.travelSubstitutionSlug) return EXERCISES[ex.travelSubstitutionSlug];
  return ex;
}

